<?php
// Meaning in Music — instrument listings API (GET + POST actions).
// Listings are stored in instruments.json; photos are saved alongside it as upload-*.

header('Content-Type: application/json; charset=utf-8');

require __DIR__ . '/config.php';

$dataFile = __DIR__ . '/instruments.json';
$uploadDir = __DIR__ . '/';
$uploadBase = 'upload-';

function readItems($file) {
    if (!file_exists($file)) {
        return array();
    }
    $raw = file_get_contents($file);
    $items = json_decode($raw, true);
    return is_array($items) ? $items : array();
}

function writeItems($file, $items) {
    $tmp = $file . '.tmp';
    file_put_contents($tmp, json_encode($items, JSON_UNESCAPED_SLASHES));
    if (!@rename($tmp, $file)) {
        file_put_contents($file, json_encode($items, JSON_UNESCAPED_SLASHES));
    }
}

function respond($code, $payload) {
    http_response_code($code);
    echo json_encode($payload);
    exit;
}

function newId() {
    return 'i_' . bin2hex(random_bytes(6)) . '_' . time();
}

function adminAuthorized($input) {
    global $ADMIN_EMAIL, $ADMIN_PASSWORD;
    $email = isset($input['email']) ? (string)$input['email'] : '';
    $password = isset($input['password']) ? (string)$input['password'] : '';
    return is_string($ADMIN_EMAIL) && is_string($ADMIN_PASSWORD)
        && hash_equals($ADMIN_EMAIL, $email)
        && hash_equals($ADMIN_PASSWORD, $password);
}

function saveUploadedImage($imageData, $uploadDir, $uploadBase) {
    // Accept data URLs generated by the admin page.
    if (strpos($imageData, 'data:image/') !== 0) {
        return $imageData; // image URL or empty — store as-is
    }
    if (!preg_match('#^data:image/(jpeg|jpg|png|webp);base64,(.*)$#s', $imageData, $m)) {
        return '';
    }
    $ext = $m[1] === 'jpg' ? 'jpg' : $m[1];
    $binary = base64_decode($m[2]);
    if ($binary === false || strlen($binary) > 8 * 1024 * 1024) {
        return '';
    }
    $name = 'inst_' . gmdate('Ymd_His') . '_' . bin2hex(random_bytes(4)) . '.' . $ext;
    if (!is_dir($uploadDir) && !@mkdir($uploadDir, 0755, true)) {
        return '';
    }
    if (file_put_contents($uploadDir . $name, $binary) === false) {
        return '';
    }
    return $uploadBase . $name;
}

function cleanItem($item, $uploadDir, $uploadBase) {
    $name = trim(isset($item['name']) ? $item['name'] : '');
    if ($name === '') {
        return null;
    }
    if (!is_string($name)) {
        $name = '';
    }
    $name = substr($name, 0, 120);

    $condition = isset($item['condition']) ? $item['condition'] : 'Good';
    if (!in_array($condition, array('Good', 'Fair', 'Great'), true)) {
        $condition = 'Good';
    }

    $details = isset($item['details']) && is_array($item['details'])
        ? array_values(array_map('trim', $item['details']))
        : array();

    $description = isset($item['description']) && is_string($item['description'])
        ? trim($item['description']) : '';
    $manufacturer = isset($item['manufacturer']) && is_string($item['manufacturer'])
        ? trim($item['manufacturer']) : '';
    $year = isset($item['year']) ? trim((string)$item['year']) : '';
    if ($year !== '' && !preg_match('/^\d{4}$/', $year)) {
        $year = '';
    }
    $notes = isset($item['notes']) && is_string($item['notes'])
        ? trim($item['notes']) : '';

    $rawImages = array();
    if (isset($item['images']) && is_array($item['images'])) {
        $rawImages = $item['images'];
    } elseif (isset($item['image']) && is_string($item['image']) && trim($item['image']) !== '') {
        $rawImages = array($item['image']);
    }
    $images = array();
    foreach ($rawImages as $img) {
        if (!is_string($img)) {
            continue;
        }
        $img = trim($img);
        if ($img === '') {
            continue;
        }
        $img = saveUploadedImage($img, $uploadDir, $uploadBase);
        if ($img !== '') {
            $images[] = $img;
        }
    }
    $images = array_values(array_unique($images));
    $images = array_slice($images, 0, 10);

    return array(
        'name' => $name,
        'condition' => $condition,
        'images' => $images,
        'description' => substr($description, 0, 2000),
        'manufacturer' => substr($manufacturer, 0, 120),
        'year' => $year,
        'notes' => substr($notes, 0, 2000),
        'details' => array_slice($details, 0, 12),
    );
}

function deleteOldUploads($oldImages, $newImages, $base) {
    foreach ($oldImages as $old) {
        if (!is_string($old)) {
            continue;
        }
        if (strpos($old, $base) === 0 && basename($old) === $old && !in_array($old, $newImages, true)) {
            $file = __DIR__ . '/' . $old;
            if (file_exists($file)) {
                @unlink($file);
            }
        }
    }
}

$method = $_SERVER['REQUEST_METHOD'];

// ---- GET: list all instruments (also used as a probe) ----
if ($method === 'GET') {
    if (isset($_GET['probe'])) {
        respond(200, array('ok' => true));
    }
    respond(200, readItems($dataFile));
}

// ---- POST: create / update / delete (admin only) ----
if ($method === 'POST') {
    $input = json_decode(file_get_contents('php://input'), true);
    if (!is_array($input)) {
        respond(400, array('error' => 'Invalid request'));
    }

    $action = isset($input['action']) ? $input['action'] : 'create';

    if ($action === 'auth') {
        if (adminAuthorized($input)) {
            respond(200, array('ok' => true));
        }
        respond(403, array('error' => 'wrong_password'));
    }

    if (!adminAuthorized($input)) {
        respond(403, array('error' => 'wrong_password'));
    }

    $items = readItems($dataFile);

    if ($action === 'delete') {
        $id = isset($input['id']) ? $input['id'] : '';
        $kept = array();
        foreach ($items as $it) {
            if ((isset($it['id']) ? $it['id'] : '') !== $id) {
                $kept[] = $it;
            } else {
                $oldImages = isset($it['images']) && is_array($it['images'])
                    ? $it['images']
                    : (isset($it['image']) ? array($it['image']) : array());
                deleteOldUploads($oldImages, array(), $uploadBase);
            }
        }
        writeItems($dataFile, $kept);
        respond(200, array('ok' => true, 'items' => $kept));
    }

    if ($action === 'update') {
        $id = isset($input['id']) ? $input['id'] : '';
        $clean = cleanItem($input, $uploadDir, $uploadBase);
        if ($clean === null) {
            respond(400, array('error' => 'Name is required'));
        }
        $updated = false;
        foreach ($items as &$it) {
            if ((isset($it['id']) ? $it['id'] : '') === $id) {
                // Remove old uploaded files that are no longer in the image set.
                $oldImages = isset($it['images']) && is_array($it['images'])
                    ? $it['images']
                    : (isset($it['image']) ? array($it['image']) : array());
                $newImages = isset($clean['images']) ? $clean['images'] : array();
                deleteOldUploads($oldImages, $newImages, $uploadBase);
                $it = array_merge($it, $clean);
                $updated = true;
                break;
            }
        }
        unset($it);
        if (!$updated) {
            respond(404, array('error' => 'Not found'));
        }
        writeItems($dataFile, $items);
        respond(200, array('ok' => true, 'items' => $items));
    }

    // create
    $clean = cleanItem($input, $uploadDir, $uploadBase);
    if ($clean === null) {
        respond(400, array('error' => 'Name is required'));
    }
    $item = $clean;
    $item['id'] = newId();
    $item['createdAt'] = date('Y-m-d');
    $items[] = $item;
    writeItems($dataFile, $items);
    respond(200, array('ok' => true, 'item' => $item, 'items' => $items));
}

respond(405, array('error' => 'Method not allowed'));